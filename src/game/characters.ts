    p4: [number, number, number, number];
    k1: [number, number, number, number];
    k2: [number, number, number, number];
    k3: [number, number, number, number];
    k4: [number, number, number, number];
    crouchP: [number, number, number, number];
    crouchK: [number, number, number, number];
    airP: [number, number, number, number];
    airK: [number, number, number, number];
    throwMove: [number, number, number, number];
